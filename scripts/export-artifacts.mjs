import { existsSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs';

const artifact = JSON.parse(readFileSync('contracts/out/ArcMandateVault.sol/ArcMandateVault.json', 'utf8'));
mkdirSync('packages/core/src/generated', { recursive: true });
const target = 'packages/core/src/generated/vault.ts';
const contract = artifact.ast?.nodes.find((node) => node.nodeType === 'ContractDefinition' && node.name === 'ArcMandateVault');
const immutableSlots = {};
for (const [id, slots] of Object.entries(artifact.deployedBytecode.immutableReferences)) {
  const declaration = contract?.nodes.find((node) => String(node.id) === id && node.mutability === 'immutable');
  if (!declaration || !['owner', 'pqPublicKey'].includes(declaration.name) || slots.some((slot) => slot.length !== 32)) {
    throw new Error(`Unrecognized immutable ${id}; rebuild with AST and review the runtime identity gate`);
  }
  immutableSlots[declaration.name] = slots;
}
if (Object.keys(immutableSlots).sort().join(',') !== 'owner,pqPublicKey') throw new Error('Missing vault immutables');
const source = '// Generated by npm run artifacts from the pinned Foundry build.\n'
  + `export const vaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
  + `export const vaultBytecode = '${artifact.bytecode.object}' as const;\n`
  + `export const vaultRuntime = '${artifact.deployedBytecode.object}' as const;\n`
  + `export const vaultImmutableSlots = ${JSON.stringify(immutableSlots, null, 2)} as const;\n`;
if (!existsSync(target) || readFileSync(target, 'utf8') !== source) writeFileSync(target, source);
